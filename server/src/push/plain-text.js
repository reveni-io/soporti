const MARKDOWN_RULES = [
  [/^[ \t]*(?:```|~~~).*$/gm, ''],
  [/<\/?[a-z][^<>\n]*>/gi, ' '],
  [/`([^`\n]+)`/g, '$1'],
  [/!\[([^\]\n]*)\]\([^)\n]*\)/g, '$1'],
  [/\[([^\]\n]+)\]\([^)\n]*\)/g, '$1'],
  [/^[ \t]{0,3}#{1,6}[ \t]+/gm, ''],
  [/^[ \t]*(?:>[ \t]?)+/gm, ''],
  [/^[ \t]*[-*_=|:][-*_=|: \t]{2,}$/gm, ''],
  [/^[ \t]*(?:[-*+]|\d+[.)])[ \t]+(?:\[[ xX]\][ \t]+)?/gm, ''],
  [/[ \t]*\|[ \t]*/g, ' '],
  [/(\*\*|__|~~)(?=\S)(.+?)\1/g, '$2'],
  [/(^|[^\w\\*])\*(?=\S)([^*\n]+?)\*(?!\w)/g, '$1$2'],
  [/(^|[^\w\\])_(?=\S)([^_\n]+?)_(?!\w)/g, '$1$2'],
  [/\\([\\`*_{}[\]()#+\-.!|>~])/g, '$1'],
]

export function toPlainText(markdown) {
  return MARKDOWN_RULES.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), markdown)
}
